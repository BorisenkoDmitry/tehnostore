async (page) => {
  await page.goto("http://localhost:9001/app/content-articles")
  await page.getByRole("button", { name: "Добавить статью", exact: true }).click()
  await page.getByRole("tab", { name: "Статья", exact: true }).click()
  const editor = page.getByRole("textbox", { name: "Содержимое статьи", exact: true })
  await editor.fill("Первый блок")
  await editor.press("Control+End")
  await page.keyboard.press("Enter")
  await page.keyboard.type("Второй блок")
  const blocks = editor.locator(".bn-block-outer")
  await blocks.first().hover()
  const source = await page.getByRole("button", { name: "Открыть меню блока", exact: true }).boundingBox()
  const target = await blocks.last().boundingBox()
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2)
  await page.mouse.down()
  await page.mouse.move(source.x + source.width / 2 + 12, source.y + source.height / 2 + 8, { steps: 4 })
  await page.mouse.move(target.x + 100, target.y + target.height + 25, { steps: 12 })
  await page.mouse.move(target.x + 105, target.y + target.height + 26)
  await page.mouse.up()
  await page.waitForFunction(() => document.querySelector('[aria-label="Содержимое статьи"] .bn-block-outer')?.textContent === "Второй блок")
  const order = await blocks.allTextContents()
  await page.getByRole("button", { name: "Отмена", exact: true }).click()
  return { dragAndDrop: true, order }
}
